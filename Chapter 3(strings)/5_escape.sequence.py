a="Suman is a good guy\n\n but not a \t\tbad guy"
print(a)

a="Hello\vworld"#\v is used to add a vertical tab space in the string.
print(a)
a="Hello\a"# \a is used to produce a beep sound.
print(a)#\a is used to produce a beep sound.

b="\U0001F600"
print(b)

c="\u2764"
print(c)

#Note:
# \n is used to add a new line in the string.   
# \t is used to add a tab space in the string.